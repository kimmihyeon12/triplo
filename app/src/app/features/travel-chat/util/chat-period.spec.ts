import { describe, expect, it } from 'vitest';
import { chatPeriod } from './chat-period';

// 2026-10-01은 목요일이다.
const TODAY = '2026-10-01';

describe('대화에서 여행 기간 읽기', () => {
  it.each([
    ['내일부터 2박3일로 짜줘', '2026-10-02', '2026-10-04'],
    ['모레부터 1박 2일', '2026-10-03', '2026-10-04'],
    ['오늘부터 당일치기', '2026-10-01', '2026-10-01'],
    ['10월 2일부터 4일까지 코스', '2026-10-02', '2026-10-04'],
    ['10월2일부터 10월4일까지', '2026-10-02', '2026-10-04'],
    ['10월 9일부터 2박3일', '2026-10-09', '2026-10-11'],
    ['이번 주말에 강릉', '2026-10-03', '2026-10-04'],
    ['다음 주말 1박2일', '2026-10-10', '2026-10-11'],
  ])('%s → %s ~ %s', (text, start, end) => {
    expect(chatPeriod(text, TODAY)).toEqual({ start, end });
  });

  it('지난 날짜는 내년으로 본다', () => {
    expect(chatPeriod('1월 3일부터 2박3일', TODAY)).toEqual({ start: '2027-01-03', end: '2027-01-05' });
  });

  it('시작일을 알 수 없으면 정하지 않는다', () => {
    expect(chatPeriod('2박3일로 짜줘', TODAY)).toBeNull();
    expect(chatPeriod('강릉 카페 추천', TODAY)).toBeNull();
  });
});
