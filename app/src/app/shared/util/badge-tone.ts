/**
 * 배지 색 이름. 컴포넌트가 아니라 순수 계층에 둔다. 어떤 색을 쓸지 고르는 일은
 * 계산이므로 util에서 하는데, 그 코드가 색 이름을 알려고 컴포넌트 파일을
 * 가져오면 계산만 하는 코드가 화면 코드에 묶인다.
 *
 * ## 배지를 쓰는 자리
 *
 * 배지는 **상태**를 알리는 표시다. 그 자리의 값이 무엇이냐에 따라 색이
 * 달라져야 뜻이 산다. 어느 여행에서나 똑같이 나오는 값은 배지가 아니라
 * 본문이다. 개수와 시간도 배지가 아니다. `장소 4`를 파란 배지로 두면
 * 바로 옆 `장소` 분류 배지와 같은 색이 되어 하나는 분류, 하나는 수량이라는
 * 것을 색으로 구분할 수 없다.
 *
 * | 쓸 것 | 쓰지 말 것 |
 * | --- | --- |
 * | 위치 미확인, 예약함, 숙박 중복 | 장소 4, 숙소 1, 2박 3일 |
 * | 관광·식사·카페 등 분류, 지역 이름 | 체류 2시간 30분, 미배치 1 |
 * | 저장 실패, 정산 제외 | 사람 이름, D-17 |
 *
 * ## 색마다의 뜻
 *
 * 한 색을 두 뜻으로 쓰지 않는다. 뜻이 겹치면 사용자가 색으로 상태를
 * 가릴 수 없어 글자를 하나하나 읽어야 한다.
 *
 * - `accent`: 지금 고른 것, 진행 중인 단계
 * - `place`·`activity`·`meal`·`cafe`·`shopping`·`other`: 일정 분류 전용. 다른 뜻으로 빌려 쓰지 않는다
 * - `region`: 지역 이름 전용
 * - `stay`: 숙소 전용
 * - `ok`: 확인·완료됨(위치 확인됨, 예약함, 저장됨)
 * - `warn`: 아직 정해지지 않음(위치 미확인, 예약 미정, 숙소 미정)
 * - `danger`: 서로 어긋남(중복, 시각 충돌, 저장 실패)
 * - `neutral`: 위 어디에도 들지 않는 보조 표시
 *
 * `warn`과 `danger`를 가르는 기준은 **사용자가 무언가를 아직 안 했는가**
 * (`warn`)와 **이미 넣은 값끼리 맞지 않는가**(`danger`)이다. 중복은 어느
 * 화면에서나 `danger`다.
 */
export type BadgeTone =
  | 'accent'
  | 'place'
  | 'region'
  | 'stay'
  | 'warn'
  | 'danger'
  | 'ok'
  | 'meal'
  | 'cafe'
  | 'activity'
  | 'shopping'
  | 'other'
  | 'neutral';
